def slim_env(env: dict[str, str]) -> dict[str, str]:
    """只保留白名单里的变量，非 ASCII 值直接丢弃并告警。

    cmd 批处理按系统 ANSI 代码页解析，值里出现中文路径基本必炸，
    所以这里主动挡掉，而不是把隐患写进文件。
    """
    out: dict[str, str] = {}
    for key in KEEP_ENV_KEYS:
        value = env.get(key)
        if value is None:
            continue
        try:
            value.encode("ascii")
        except UnicodeEncodeError:
            print(f"[make_launchers] 跳过非 ASCII 值: {key}", file=sys.stderr)
            continue
        out[key] = value
    return out


def _quote(value: str) -> str:
    """cmd 的 set 值里有特殊字符时必须整体加引号，否则 & | > ^ 会被当语法。"""
    return value


def write_cmd(path: Path, env: dict[str, str], workdir: Path, command: str, logfile: Path) -> None:
    """写一个自包含的启动器。

    结构：@echo off → 切目录 → 逐条 set → 起命令并把输出重定向到日志。
    """
    # 注意：.cmd 用纯 ASCII 写。
    # 原因：cmd.exe 默认按系统 ANSI 代码页（中文 Windows 是 GBK/936）解析批处理文件。
    # 如果文件是 UTF-8 且含中文注释，cmd 会把 UTF-8 字节按 GBK 解码成乱码，
    # 乱码里的残留字符会被当成命令执行，导致整个启动器失效（表现为日志只有 started 一行、
    # 进程立刻退出、端口不监听）。注释一律用英文可以彻底避开这个坑。
    lines = [
        "@echo off",
        "REM Auto-generated by deploy/scripts/make_launchers.py - do not edit by hand.",
        "REM All environment variables are baked in below; no dependency on caller env.",
        "",
        f'cd /d "{workdir}"',
        "",
    ]
    for key, value in env.items():
        # set "K=V" 形式对含空格/特殊字符的值最安全
        lines.append(f'set "{key}={value}"')
    lines += [
        "",
        f'echo [launcher] started %DATE% %TIME% >> "{logfile}"',
        f'{command} >> "{logfile}" 2>&1',
        "",
    ]
    content = "\r\n".join(lines)
    # 落盘前强校验：.cmd 必须纯 ASCII，否则 cmd.exe 会按 GBK 误解析导致启动器失效
    try:
        content.encode("ascii")
    except UnicodeEncodeError as exc:
        raise SystemExit(f"[make_launchers] 生成失败：{path.name} 含非 ASCII 字符 -> {exc}")
    path.write_text(content, encoding="ascii", newline="")
    print(f"[make_launchers] 生成 {path}（ASCII，{len(lines)} 行）")


def write_vbs(path: Path, cmd_path: Path, workdir: Path) -> None:
    """生成一个隐藏窗口的 VBS 启动器。

    为什么需要它：
    用 WMI 的 Win32_Process.Create 直接执行 `cmd /c xxx.cmd` 时，Windows 会给这个
    cmd 配一个真实控制台窗口。那个窗口就是服务的载体——用户看到两个空白 cmd 窗口，
    一旦关掉，里面的 uvicorn/java 立刻收到 ^C 退出，表现为「关窗口后登录就 502」。

    wscript.exe 是 GUI 子系统程序，自身不创建控制台；它用
    WScript.Shell.Run(..., 0, False) 拉起 cmd 时指定窗口样式 0（隐藏），
    于是整条进程链都在无窗口状态下运行，用户看不到任何窗口，也就没有可误关的东西。
    """
    lines = [
        'Set sh = CreateObject("WScript.Shell")',
        f'sh.CurrentDirectory = "{workdir}"',
        'sh.Run "cmd.exe /c ""' + str(cmd_path) + '""", 0, False',
        '',
    ]
    content = "\r\n".join(lines)
    # VBS 用系统 ANSI 读取最稳；这里保证纯 ASCII（路径里若含中文会被挡下并报错）
    try:
        content.encode("ascii")
    except UnicodeEncodeError as exc:
        raise SystemExit(f"[make_launchers] 生成失败：{path.name} 含非 ASCII 字符 -> {exc}")
    path.write_text(content, encoding="ascii", newline="")
    print(f"[make_launchers] 生成 {path}（隐藏窗口启动器）")


def main() -> int:
    RUN_DIR.mkdir(parents=True, exist_ok=True)
    (ROOT / "test-artifacts").mkdir(parents=True, exist_ok=True)

    cfg = p7_env.load()

    # ---- Java ----
    java_env = slim_env(p7_up.build_env(cfg))
    java_env.setdefault("JAVA_TOOL_OPTIONS", "-Dfile.encoding=UTF-8")
    profiles = os.getenv("P7_SPRING_PROFILES", "gate-probe")
    java_exe = os.getenv("JAVA_EXE", "java")
    java_cmd = f'"{java_exe}" -jar "{p7_up.JAVA_JAR}"'
    if profiles:
        java_cmd += f" --spring.profiles.active={profiles}"
    write_cmd(
        RUN_DIR / "java.cmd",
        java_env,
        ROOT / "backend" / "java-api",
        java_cmd,
        ROOT / "test-artifacts" / "p7-java-fg.log",
    )

    # ---- Python AI ----
    ai_env = {
        **AI_PROVIDER,
        "INTERNAL_TOKEN": cfg["INTERNAL_TOKEN"],
        "STORAGE_ROOT": cfg["AI_STORAGE_ROOT"],
        "PYTHONIOENCODING": "utf-8",
        "PYTHONUTF8": "1",
    }
    ai_cmd = (
        f'"{sys.executable}" -m uvicorn app.main:app '
        f"--host 127.0.0.1 --port 8000 --timeout-keep-alive 75"
    )
    write_cmd(
        RUN_DIR / "ai.cmd",
        ai_env,
        ROOT / "backend" / "ai-api",
        ai_cmd,
        ROOT / "test-artifacts" / "dev-ai.log",
    )

    # 再生成隐藏窗口启动器
    write_vbs(RUN_DIR / "java-hidden.vbs", RUN_DIR / "java.cmd", ROOT / "backend" / "java-api")
    write_vbs(RUN_DIR / "ai-hidden.vbs", RUN_DIR / "ai.cmd", ROOT / "backend" / "ai-api")

    # 供 PowerShell 读取的关键参数
    meta = {
        "java_cmd": str(RUN_DIR / "java.cmd"),
        "ai_cmd": str(RUN_DIR / "ai.cmd"),
        "java_vbs": str(RUN_DIR / "java-hidden.vbs"),
        "ai_vbs": str(RUN_DIR / "ai-hidden.vbs"),
        "java_port": 8080,
        "ai_port": 8000,
        "profiles": profiles,
    }
    (RUN_DIR / "meta.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"[make_launchers] 完成 -> {RUN_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
