"""生成后端启动器（.cmd），把环境变量直接写死进去。

为什么需要这一步：
`_dev_up_java.py` / `_dev_up_ai.py` 是用 subprocess.Popen 起子进程、再 wait() 等它。
这样 java/uvicorn 永远是那个 python 进程的子进程。如果启动它的 shell 处在一个
Windows「作业对象」(job object) 里（IDE 终端、CI、某些 agent 的沙箱都是），
作业结束时会连带杀掉整棵进程树 —— 表现为「关掉窗口后后端就没了」。

改成用 .cmd 启动器 + WMI 创建进程：
  - 环境变量在 .cmd 里用 set 固化成字面量，不再依赖父进程
  - 由 WMI (Win32_Process.Create) 拉起，新进程不属于调用者的作业对象，父进程退出不受影响

用法（由 deploy\\scripts\\start-backend.ps1 调用）：
    python deploy\\scripts\\make_launchers.py
"""

